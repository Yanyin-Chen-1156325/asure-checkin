import { PageHeading } from "@/components/ui/page-heading";
import { requirePageRole } from "@/lib/auth/current-session";
import { TemplateEditor } from "@/components/templates/template-editor";

export default async function AgreementDetailPage({ params }: Readonly<{ params: Promise<{ id: string }> }>) {
  await requirePageRole("owner");
  const { id } = await params;
  return (
    <div className="mx-auto max-w-6xl">
      <PageHeading eyebrow="Agreement" title="Template editor" description="Only supported formatting is stored. Guest details and signature blocks are generated by the system." />
      <TemplateEditor id={id} />
    </div>
  );
}
